import { posixCurlCommand } from '../agent-hooks/hook-post-command'
import { buildWindowsAgentHookPostCommand } from '../agent-hooks/installer-utils'
import {
  buildPosixHookPayloadCapture,
  buildPosixHookSpoolLines,
  buildWindowsHookEnvironmentGuardLines
} from '../agent-hooks/hook-stdin-contract'

export type CommandCodeManagedScriptTarget = 'local' | 'posix'

export function buildCommandCodeManagedScript(
  target: CommandCodeManagedScriptTarget = 'local'
): string {
  if (target === 'local' && process.platform === 'win32') {
    return [
      '@echo off',
      'setlocal',
      'if "%MADANG_AGENT_HOOK_PORT%"=="" if defined MADANG_AGENT_HOOK_ENDPOINT if exist "%MADANG_AGENT_HOOK_ENDPOINT%" call "%MADANG_AGENT_HOOK_ENDPOINT%" 2>nul',
      'if "%MADANG_AGENT_HOOK_TOKEN%"=="" if not "%MADANG_AGENT_HOOK_PORT%"=="" call :sourceEndpointByPort',
      ...buildWindowsHookEnvironmentGuardLines(),
      buildWindowsAgentHookPostCommand('command-code'),
      'exit /b 0',
      ':sourceEndpointByPort',
      'if not defined APPDATA exit /b 0',
      'if exist "%APPDATA%\\madang-dev\\agent-hooks" for /r "%APPDATA%\\madang-dev\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      // Per-worktree `pnpm dev` profiles live one level down; FOR /R cannot take a FOR variable as its root.
      'if "%MADANG_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\madang-dev-wt" for /d %%P in ("%APPDATA%\\madang-dev-wt\\*") do call :scanEndpointDir "%%~fP\\agent-hooks"',
      'if "%MADANG_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\orca\\agent-hooks" for /r "%APPDATA%\\orca\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':scanEndpointDir',
      'if not "%MADANG_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'if exist "%~1" for /r "%~1" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':maybeSourceEndpoint',
      'if not "%MADANG_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set MADANG_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do if "%%P"=="%MADANG_AGENT_HOOK_PORT%" call "%~1" 2>nul',
      'exit /b 0',
      ''
    ].join('\r\n')
  }

  return [
    '#!/bin/sh',
    ...buildPosixHookPayloadCapture(),
    ...buildPosixHookSpoolLines('command-code'),
    '__orca_read_ancestor_var() {',
    '  __orca_name="$1"',
    '  __orca_pid="${PPID:-}"',
    '  while [ -n "$__orca_pid" ] && [ "$__orca_pid" != "0" ] && [ "$__orca_pid" != "1" ]; do',
    '    __orca_value=""',
    '    if [ -r "/proc/$__orca_pid/environ" ]; then',
    '      __orca_value=$(tr "\\000" "\\n" < "/proc/$__orca_pid/environ" 2>/dev/null | sed -n "s/^${__orca_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -z "$__orca_value" ]; then',
    '      __orca_value=$(ps eww -p "$__orca_pid" -o command= 2>/dev/null | tr " " "\\n" | sed -n "s/^${__orca_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -n "$__orca_value" ]; then',
    '      printf "%s\\n" "$__orca_value"',
    '      return 0',
    '    fi',
    '    __orca_pid=$(ps -o ppid= -p "$__orca_pid" 2>/dev/null | tr -d " ")',
    '  done',
    '  return 1',
    '}',
    '__orca_fill_from_ancestor() {',
    '  __orca_name="$1"',
    '  case "$__orca_name" in',
    '    MADANG_AGENT_HOOK_ENDPOINT) [ -z "${MADANG_AGENT_HOOK_ENDPOINT:-}" ] || return 0 ;;',
    '    MADANG_AGENT_HOOK_PORT) [ -z "${MADANG_AGENT_HOOK_PORT:-}" ] || return 0 ;;',
    '    MADANG_AGENT_HOOK_TOKEN) [ -z "${MADANG_AGENT_HOOK_TOKEN:-}" ] || return 0 ;;',
    '    MADANG_AGENT_HOOK_ENV) [ -z "${MADANG_AGENT_HOOK_ENV:-}" ] || return 0 ;;',
    '    MADANG_AGENT_HOOK_VERSION) [ -z "${MADANG_AGENT_HOOK_VERSION:-}" ] || return 0 ;;',
    '    MADANG_PANE_KEY) [ -z "${MADANG_PANE_KEY:-}" ] || return 0 ;;',
    '    MADANG_TAB_ID) [ -z "${MADANG_TAB_ID:-}" ] || return 0 ;;',
    '    MADANG_WORKTREE_ID) [ -z "${MADANG_WORKTREE_ID:-}" ] || return 0 ;;',
    '    MADANG_AGENT_LAUNCH_TOKEN) [ -z "${MADANG_AGENT_LAUNCH_TOKEN:-}" ] || return 0 ;;',
    '    *) return 0 ;;',
    '  esac',
    '  __orca_value=$(__orca_read_ancestor_var "$__orca_name") || return 0',
    '  [ -n "$__orca_value" ] && export "$__orca_name=$__orca_value"',
    '}',
    '__orca_endpoint_value() {',
    '  __orca_endpoint_name="$1"',
    '  __orca_endpoint_path="$2"',
    '  sed -n "s/^${__orca_endpoint_name}=//p" "$__orca_endpoint_path" 2>/dev/null | head -n 1',
    '}',
    '__orca_fill_from_endpoint_file() {',
    '  __orca_endpoint_path="$1"',
    '  [ -r "$__orca_endpoint_path" ] || return 0',
    '  __orca_endpoint_port=$(__orca_endpoint_value MADANG_AGENT_HOOK_PORT "$__orca_endpoint_path")',
    '  if [ -n "${MADANG_AGENT_HOOK_PORT:-}" ] && [ -n "$__orca_endpoint_port" ] && [ "$__orca_endpoint_port" != "$MADANG_AGENT_HOOK_PORT" ]; then',
    '    return 0',
    '  fi',
    '  for __orca_endpoint_name in MADANG_AGENT_HOOK_PORT MADANG_AGENT_HOOK_TOKEN MADANG_AGENT_HOOK_ENV MADANG_AGENT_HOOK_VERSION; do',
    '    eval "__orca_current=\\${$__orca_endpoint_name:-}"',
    '    [ -z "$__orca_current" ] || continue',
    '    __orca_endpoint_value=$(__orca_endpoint_value "$__orca_endpoint_name" "$__orca_endpoint_path")',
    '    [ -n "$__orca_endpoint_value" ] && export "$__orca_endpoint_name=$__orca_endpoint_value"',
    '  done',
    '}',
    '# Recover pane/hook metadata from the parent TUI after Command Code sanitizes hook env.',
    'for __orca_name in MADANG_AGENT_HOOK_ENDPOINT MADANG_AGENT_HOOK_PORT MADANG_AGENT_HOOK_TOKEN MADANG_AGENT_HOOK_ENV MADANG_AGENT_HOOK_VERSION MADANG_PANE_KEY MADANG_TAB_ID MADANG_WORKTREE_ID MADANG_AGENT_LAUNCH_TOKEN; do',
    '  __orca_fill_from_ancestor "$__orca_name"',
    'done',
    'if [ -n "$MADANG_AGENT_HOOK_ENDPOINT" ] && [ -r "$MADANG_AGENT_HOOK_ENDPOINT" ]; then',
    '  __orca_fill_from_endpoint_file "$MADANG_AGENT_HOOK_ENDPOINT"',
    'fi',
    '# Recover stripped token metadata by matching the preserved loopback port.',
    'if [ -z "$MADANG_AGENT_HOOK_TOKEN" ] && [ -n "$MADANG_AGENT_HOOK_PORT" ]; then',
    '  for endpoint in \\',
    '    "$HOME/Library/Application Support/madang-dev/agent-hooks"/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/madang-dev/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/madang-dev/agent-hooks"/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/madang-dev/agent-hooks/endpoint.env" \\',
    '    "$HOME/Library/Application Support/madang-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/madang-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/orca/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca/agent-hooks/endpoint.env"; do',
    '    [ -r "$endpoint" ] || continue',
    '    endpoint_port=$(sed -n "s/^MADANG_AGENT_HOOK_PORT=//p" "$endpoint" | head -n 1)',
    '    if [ "$endpoint_port" = "$MADANG_AGENT_HOOK_PORT" ]; then',
    '      __orca_fill_from_endpoint_file "$endpoint"',
    '      break',
    '    fi',
    '  done',
    'fi',
    'if [ -z "$MADANG_AGENT_HOOK_PORT" ] || [ -z "$MADANG_AGENT_HOOK_TOKEN" ] || [ -z "$MADANG_PANE_KEY" ]; then',
    '  spool_hook_event',
    '  exit 0',
    'fi',
    // Bound stalled posts and pipe large payloads through stdin to avoid EDR command-line false positives.
    `printf '%s' "$payload" | ${posixCurlCommand()} -sS -X POST "http://127.0.0.1:\${MADANG_AGENT_HOOK_PORT}/hook/command-code" \\`,
    '  --connect-timeout 0.5 --max-time 1.5 \\',
    '  -H "Content-Type: application/x-www-form-urlencoded" \\',
    '  -H "X-Orca-Agent-Hook-Token: ${MADANG_AGENT_HOOK_TOKEN}" \\',
    '  --data-urlencode "paneKey=${MADANG_PANE_KEY}" \\',
    '  --data-urlencode "tabId=${MADANG_TAB_ID}" \\',
    '  --data-urlencode "launchToken=${MADANG_AGENT_LAUNCH_TOKEN}" \\',
    '  --data-urlencode "worktreeId=${MADANG_WORKTREE_ID}" \\',
    '  --data-urlencode "env=${MADANG_AGENT_HOOK_ENV}" \\',
    '  --data-urlencode "version=${MADANG_AGENT_HOOK_VERSION}" \\',
    '  --data-urlencode "payload@-" >/dev/null 2>&1 || spool_hook_event',
    'exit 0',
    ''
  ].join('\n')
}
